import Foundation

@main @MainActor
struct GoalModelTests {
    static func main() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("FocoGoalModel-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: dir) }
        let store = FocusStore(directory: dir)
        let now = Date()
        let first = try store.addGoal(title: "Primero", targetHours: 3)
        let second = try store.addGoal(title: "Segundo", targetHours: nil)
        let task = try store.addTask(title: "Tarea", day: now, goalID: first.id)
        let loose = try store.addTask(title: "Sin grupo", day: now)
        let otherTask = try store.addTask(title: "Otra tarea", day: now, goalID: second.id)
        let model = FocoModel(store: store)
        precondition(Set(model.availableTasks.map(\.id)) == Set([task.id, loose.id, otherTask.id]),
                     "No selected goal shows all available tasks")
        model.chooseGoalID(first.id)
        precondition(model.availableTasks.map(\.id) == [task.id], "Only tasks assigned to the selected goal appear")
        model.chooseGoalID(nil)
        precondition(model.availableTasks.count == 3, "Clearing the goal restores all available tasks")
        model.chooseTask(task)
        precondition(model.selectedGoalID == first.id && model.selectedTaskID == task.id)
        model.chooseGoalID(second.id)
        precondition(model.selectedTaskID == nil && model.selectedGoalID == second.id)
        model.chooseTask(loose)
        model.chooseGoalID(first.id)
        model.tick()
        precondition(model.selectedTaskID == nil && model.selectedGoalID == first.id, "Selecting a goal clears a previously selected unassigned task")
        model.chooseTask(task)
        precondition(model.editTask(task, title: task.title, day: now, goalID: second.id))
        precondition(model.selectedGoalID == second.id, "Editing selected task synchronizes the next block goal")
        precondition(model.editTask(task, title: task.title, day: now, goalID: first.id))
        precondition(Set(model.availableTasks.map(\.id)) == Set([task.id]), "An edited task appears under its current goal")
        model.chooseGoal(second)
        precondition(model.section == .focus && model.selectedTaskID == nil && model.selectedGoalID == second.id)
        model.chooseTask(task)
        precondition(model.finishGoal(first, outcome: .partial, note: "Avance parcial"))
        precondition(model.selectedTaskID == nil && model.selectedGoalID == nil && !model.canFocusTask(task), "Closed goal clears unavailable selection")
        model.deleteGoal(first)
        precondition(model.deletedGoal != nil && !model.goals.contains { $0.id == first.id })
        model.undoGoalDelete()
        precondition(model.deletedGoal == nil && model.goals.contains { $0.id == first.id })
        model.deleteGoal(first)
        model.dismissExpiredGoalUndo(at: now.addingTimeInterval(30))
        precondition(model.deletedGoal == nil && !model.goals.contains { $0.id == first.id }, "Notice expiry leaves deletion in place")
        precondition(model.saveGoal(second, title: "Segundo editado", hours: 1.5))
        precondition(model.goals.first { $0.id == second.id }?.targetSeconds == 5400)
        let liveTask = try store.addTask(title: "Para deshacer", day: now, goalID: second.id)
        model.tick(); model.chooseTask(liveTask)
        model.deleteGoal(second)
        precondition(model.selectedTaskID == liveTask.id && model.selectedGoalID == nil)
        model.undoGoalDelete()
        precondition(model.selectedTaskID == liveTask.id && model.selectedGoalID == second.id, "Goal undo synchronizes selection without relabeling time")
        print("PASS goal model: task/goal selection, direct focus, closure, undo expiry and decimal target")
    }
}
