const fs=require('node:fs');const vm=require('node:vm');const assert=require('node:assert/strict');
const context=vm.createContext({Date});
vm.runInContext(fs.readFileSync(__dirname+'/../Extension/rules.js','utf8')+';globalThis.testRules=rulesFor;globalThis.testValid=validSite;',context);
const rules=(s,t)=>JSON.parse(JSON.stringify(context.testRules(s,t)));
const session={id:'test',startedAt:1000,duration:60,firm:true};
assert.deepEqual(rules(null,1000),[]);
assert.equal(rules(session,1000).length,3);
assert.deepEqual(rules(session,1060),[]);
assert.equal(rules({...session,blockWhatsAppWeb:true},1001).length,4);
assert.deepEqual(rules({...session,sites:[]},1001),[]);
const custom={...session,sites:[{host:'example.com',path:'/study'}]};
const r=rules(custom,1001)[0];const regex=new RegExp(r.condition.regexFilter);
for(const url of ['https://example.com/study','https://example.com/study/video','https://sub.example.com/study?x=1']) assert(regex.test(url));
for(const url of ['https://example.com/studying','https://example.com.evil.org/study','https://other.org/study','https://example.com/Study']) assert(!regex.test(url));
for(const host of ['<all_urls>','evil.com|safe.com','example.com^','localhost','127.0.0.1','example.com/other']) assert(!context.testValid({host,path:'/'}));
assert(!context.testValid({host:'example.com',path:'/foo?x=1'}));
assert.throws(()=>rules({...session,sites:[{host:'<all_urls>',path:'/'}]},1001));
const manifest=JSON.parse(fs.readFileSync(__dirname+'/../Extension/manifest.json'));
assert(!manifest.host_permissions || manifest.host_permissions.length===0);
assert.deepEqual(manifest.optional_host_permissions,['*://*/*']);
assert(!manifest.permissions.includes('tabs')&&!manifest.permissions.includes('scripting'));
assert(!manifest.content_scripts);
assert(manifest.content_security_policy.extension_pages.includes("object-src 'none'"));
console.log('Extension checks passed: scoped custom domains/paths, escaping, expiration, optional-only host permissions, no content scripts.');

assert.equal(rules({...session,pausedAt:1010},2000).length,3,'paused session keeps blocking beyond original deadline');
assert.equal(context.sessionElapsed({...session,pausedAt:1010},2000),10);
assert.equal(context.sessionDeadline({...session,pausedAt:1010}),null);
const resumed={...session,pauses:[{start:1010,end:2000}]};
assert.equal(context.sessionElapsed(resumed,2049),59);
assert.equal(rules(resumed,2049).length,3);
assert.deepEqual(rules(resumed,2050),[]);
console.log('PASS pause keeps rules active, freezes elapsed and shifts expiration after resume');
